#!/usr/bin/env python3
"""Real Docker check: RO project, isolated staging, native contract and host commit."""
import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
from unittest.mock import patch
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from righaven import docker_runtime as runtime, state
from righaven.progress import create_job
from righaven.resource_budget import ResourceBudget
from righaven.task_staging import TaskStaging

CODE = r'''
import errno,json,sys
from pathlib import Path
sys.path.insert(0,'/opt/righaven-worker')
import run_agent
import openai_compatible
job=json.load(open('/job.json')); output=Path('/mnt/user-data/outputs/workspace')/job['run_id']
def generate(model,prompt,output,timeout,progress=None):
    for path in ['/mnt/user-data/approved.txt','/workspace/project/approved.txt','/mnt/user-data/outputs/previous.txt']:
        try:Path(path).write_text('corrupted')
        except OSError as error:assert error.errno in (errno.EROFS,errno.EACCES),error
        else:raise AssertionError('Project is writable: '+path)
    (output/'work').mkdir(exist_ok=True);(output/'frames').mkdir(exist_ok=True)
    (output/'frames/frame.png').write_bytes(b'linked frame retained')
    (output/'report.txt').write_text('verified report')
    if job.get('simulate_failure'):raise RuntimeError('Controlled provider failure after saved output')
    name=str(output/'report.txt')
    item={'path':name,'role':'report','format':'text','open_with':'editor','editability':'text',
          'reopen':{'status':'passed','evidence':'read back'},'limitations':[]}
    handoff={'task':'Native report','source_files':['/mnt/user-data/approved.txt'], 'output_files':[name],'previews':[],
             'checks':[{'name':'Read back','status':'passed','evidence':'Read actual text'}], 'warnings':[],
             'delivery':{'source_status':'not_applicable','source_note':'report','files':[item]}}
    (output/'handoff.json').write_text(json.dumps(handoff))
    return 'Observed report generated by the isolated worker'
openai_compatible.run=generate
sys.argv=['run_agent.py','/job.json']
try:sys.exit(run_agent.main())
except RuntimeError as error:
    print(json.dumps({'ok':False,'error':str(error)}));sys.exit(17)

'''


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--image',default=os.getenv('RIGHAVEN_SANDBOX_IMAGE','righaven-sandbox:0.1.0'));args=parser.parse_args()
    repo=Path(__file__).resolve().parents[1]
    with tempfile.TemporaryDirectory(prefix='task-staging-') as temporary:
        root=Path(temporary); project=root/'project';project.mkdir(mode=0o755)
        (project/'outputs').mkdir(mode=0o755)
        (project/'approved.txt').write_text('approved baseline');(project/'approved.txt').chmod(0o644)
        (project/'outputs/previous.txt').write_text('previous delivery');(project/'outputs/previous.txt').chmod(0o644)
        with patch.object(state,'STATE',root/'state'),patch.object(runtime,'host_path',side_effect=str),patch('righaven.resource_budget.BUDGET',ResourceBudget()):
            for identifier,failed in [('rh-job-111111111111',True),('rh-job-222222222222',False)]:
                stage=TaskStaging(root/'state',project,'workspace',identifier);stage.prepare()
                progress=create_job(project,identifier,'workspace','openai','fixture')
                # Fixtures run as the executor's UID; Docker worker drops DAC capabilities.
                stage.output.chmod(0o777);progress.parent.chmod(0o777)
                for file in progress.parent.iterdir():file.chmod(0o666)
                job=root/(identifier+'.json');job.write_text(json.dumps({'agent':'workspace','run_id':identifier,'engine':'openai','model':'fixture','skills':[],'instructions':'','task':'Create the test report','timeout':60,'purpose':'work','simulate_failure':failed}));job.chmod(0o644)
                command=runtime.base_arguments(identifier)+stage.mounts(runtime.mount,progress)+[
                    '--user',str(os.getuid())+':'+str(os.getgid()),'--mount',runtime.mount(repo/'righaven','/opt/righaven-worker',True),'--mount',runtime.mount(job,'/job.json',True),args.image,'python3','-c',CODE]
                try:
                    result=subprocess.run(['docker',*command],capture_output=True,text=True,timeout=60)
                    runtime.remove(identifier)  # Validation starts only after all writers stop.
                    if failed:
                        assert result.returncode==17,result.stderr
                        stage.quarantine();assert not stage.destination.exists()
                        assert (stage.output/'report.txt').exists()
                    else:
                        assert result.returncode==0,result.stderr
                        value=json.loads(result.stdout);stage.publish(value)
                        assert (stage.destination/'frames/frame.png').read_bytes()==b'linked frame retained'
                        assert not stage.output.exists(),'Successful staging duplicated project storage'
                        assert stage.publish(value)['output_transaction']['status']=='published'
                    assert (project/'approved.txt').read_text()=='approved baseline'
                    assert (project/'outputs/previous.txt').read_text()=='previous delivery'
                finally:runtime.remove(identifier)
    print('Task isolation Docker OK: project writes rejected; failed files quarantined; native handoff verified; complete tree published atomically without replacing prior deliveries.')


if __name__=='__main__':main()
